// 스타일의 시리즈 목록 반환 (없으면 office로 폴백)
export function getSeriesList(styleId) {
  return SERIES_POOL[styleId] || SERIES_POOL.office;
}

export function getSeriesById(styleId, seriesId) {
  return getSeriesList(styleId).find((s) => s.id === seriesId) || null;
}
